static uint32_t operand_cimmshl6(rv_inst inst, rv_isa isa)
{
    int imm = extract32(inst, 12, 1) << 5 |
        extract32(inst, 2, 5);
    if (isa == rv128) {
        imm = imm ? imm : 64;
    }
    return imm;
}

static uint32_t operand_cimmshr6(rv_inst inst, rv_isa isa)
{
    int imm = extract32(inst, 12, 1) << 5 |
        extract32(inst, 2, 5);
    if (isa == rv128) {
        imm = imm | (imm & 32) << 1;
        imm = imm ? imm : 64;
    }
    return imm;
}

